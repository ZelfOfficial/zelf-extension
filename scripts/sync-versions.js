const fs = require("fs");
const path = require("path");

const formatBuildDate = (date = new Date()) => {
    const year = date.getFullYear();
    const month = String(date.getMonth() + 1).padStart(2, "0");
    const day = String(date.getDate()).padStart(2, "0");
    let hours = date.getHours();
    const minutes = String(date.getMinutes()).padStart(2, "0");
    const ampm = hours >= 12 ? "pm" : "am";
    hours = hours % 12;
    hours = hours ? hours : 12;
    return `${year}-${month}-${day} ${hours}:${minutes} ${ampm}`;
};

const getExistingVersionData = (filePath) => {
    try {
        if (!fs.existsSync(filePath)) return null;
        const content = fs.readFileSync(filePath, "utf8");
        const versionMatch = content.match(/APP_VERSION\s*=\s*["']([^"']+)["']/);
        const dateMatch = content.match(/APP_BUILD_DATE\s*=\s*["']([^"']+)["']/);
        return {
            version: versionMatch ? versionMatch[1] : null,
            date: dateMatch ? dateMatch[1] : null,
        };
    } catch {
        return null;
    }
};

const syncVersions = (options = {}) => {
    const forceUpdateDate = typeof options === "boolean" ? options : Boolean(options.forceDate);
    const packagePath = path.join(__dirname, "../package.json");
    const manifestChromePath = path.join(__dirname, "../configurations/manifest.json");
    const manifestFirefoxPath = path.join(__dirname, "../configurations/extension/firefox/manifest.json");
    const versionTsPath = path.join(__dirname, "../src/environments/version.ts");

    const packageJson = JSON.parse(fs.readFileSync(packagePath, "utf8"));
    const newVersion = packageJson.version;
    const existing = getExistingVersionData(versionTsPath);

    // Update timestamp if force requested, if version changed, or if not yet set
    const buildDate = (forceUpdateDate || !existing?.date || existing?.version !== newVersion)
        ? formatBuildDate(new Date())
        : existing.date;

    console.log(`Syncing version ${newVersion} (${buildDate}) across all files`);

    if (fs.existsSync(manifestChromePath)) {
        const manifestChrome = JSON.parse(fs.readFileSync(manifestChromePath, "utf8"));
        manifestChrome.version = newVersion;
        manifestChrome.version_name = `${newVersion} (${buildDate})`;
        fs.writeFileSync(manifestChromePath, JSON.stringify(manifestChrome, null, 4) + "\n");
    }

    if (fs.existsSync(manifestFirefoxPath)) {
        const manifestFirefox = JSON.parse(fs.readFileSync(manifestFirefoxPath, "utf8"));
        manifestFirefox.version = newVersion;
        manifestFirefox.version_name = `${newVersion} (${buildDate})`;
        fs.writeFileSync(manifestFirefoxPath, JSON.stringify(manifestFirefox, null, 4) + "\n");
    }

    const versionTsContent = `// Auto-generated by scripts/sync-versions.js - do not edit directly
export const APP_VERSION = "${newVersion}";
export const APP_BUILD_DATE = "${buildDate}";

export function getAppVersion(): string {
    try {
        if (typeof chrome !== "undefined" && chrome.runtime?.getManifest) {
            const manifest = chrome.runtime.getManifest();
            if (manifest?.version) {
                return manifest.version;
            }
        }
        if (typeof browser !== "undefined" && browser.runtime?.getManifest) {
            const manifest = browser.runtime.getManifest();
            if (manifest?.version) {
                return manifest.version;
            }
        }
    } catch {
        // Fallback to static version
    }
    return APP_VERSION;
}

export function getAppBuildDate(): string {
    try {
        if (typeof chrome !== "undefined" && chrome.runtime?.getManifest) {
            const manifest = chrome.runtime.getManifest() as any;
            if (manifest?.version_name) {
                const match = manifest.version_name.match(/\\((.+)\\)/);
                if (match?.[1]) return match[1];
            }
        }
        if (typeof browser !== "undefined" && browser.runtime?.getManifest) {
            const manifest = browser.runtime.getManifest() as any;
            if (manifest?.version_name) {
                const match = manifest.version_name.match(/\\((.+)\\)/);
                if (match?.[1]) return match[1];
            }
        }
    } catch {
        // Fallback to static date
    }
    return APP_BUILD_DATE;
}
`;

    fs.writeFileSync(versionTsPath, versionTsContent);

    console.log(`Versions synced to ${newVersion} (${buildDate})`);
    return { version: newVersion, date: buildDate };
};

if (require.main === module) {
    syncVersions({ forceDate: true });
}

module.exports = { syncVersions, formatBuildDate };
